// Pure board logic for scripts/kanban.mjs (tested in tests/kanban.test.ts).
// Cards come from three places:
//   - plan.md §1 MVP table (T0–T6), status taken from the plan's Status column
//   - plan.md §9 prioritization table (B1…, plus triggered T-1…)
//   - tasks/X<n>.md ad-hoc cards (bugs, small features) that don't need a plan.md row
// kanban.state.json moves backlog and ad-hoc cards: { "B2": { "status": "ready", "branch": "…", "note": "…" } }.
// The old form { "B2": "review" } is still read.

export const STATUSES = ["backlog", "ready", "in_progress", "blocked", "review", "done"];
const SIZE_DAYS = { S: 2, M: 4, L: 8 };

const cells = (line) => line.split("|").slice(1, -1).map((c) => c.trim());
const clean = (t) => t.replace(/\*\*/g, "").replace(/`/g, "");

/** Normalize one state entry (string or object) to { status, branch?, note?, prio? }. */
export function normEntry(v) {
  if (v == null) return { status: "backlog" };
  const e = typeof v === "string" ? { status: v } : { ...v };
  if (!STATUSES.includes(e.status)) throw new Error(`unknown status "${e.status}" (use ${STATUSES.join(", ")})`);
  return e;
}

/** Parse a tasks/X<n>.md card: "# X1: Title" heading, optional "Type: bug" / "Size: S" lines. */
export function parseTaskFile(id, text) {
  const head = /^#\s+(?:[A-Z]+\d+)?\s*[:\-–]?\s*(.+)$/m.exec(text);
  const type = /^Type:\s*(\w+)/im.exec(text)?.[1] ?? "task";
  const size = /^Size:\s*([SML])\b/im.exec(text)?.[1] ?? "S";
  return { id, item: head?.[1]?.trim() ?? id, type, size, why: "", deps: "", prio: "0", adhoc: true };
}

/** All cards with their column. taskFiles: { [id]: markdown } for every tasks/*.md (B- and X- ids). */
export function loadCards(planText, rawState = {}, taskFiles = {}) {
  const state = Object.fromEntries(Object.entries(rawState).map(([k, v]) => [k, normEntry(v)]));

  const mvp = planText.split("\n").filter((l) => /^\| \*\*T\d\*\* \|/.test(l)).map((l) => {
    const [id, name, , done, deps, status] = cells(l).map(clean);
    const col = /^done/i.test(status) ? "done" : /^in progress/i.test(status) ? "in_progress" : /^(code complete|repo initialized)/i.test(status) ? "review" : "backlog";
    return { id, item: name, done, deps, statusText: status, status: col, mvp: true };
  });

  const at = planText.indexOf("### Prioritization");
  const sect = at >= 0 ? planText.slice(at) : "";
  const planned = sect.split("\n").filter((l) => /^\| (\d+|—) \| /.test(l)).map((l) => {
    const [prio, id, item, type, size, why, deps] = cells(l).map(clean);
    return { prio, id, item, type, size, why, deps, triggered: prio === "—" };
  });
  const known = new Set(planned.map((b) => b.id));
  const adhoc = Object.entries(taskFiles).filter(([id]) => !known.has(id) && /^X\d+$/.test(id)).map(([id, t]) => parseTaskFile(id, t));

  const backlog = [...adhoc, ...planned].map((b) => {
    const s = state[b.id] ?? { status: "backlog" };
    return { ...b, ...s, hasTask: b.id in taskFiles, prioNum: s.prio ?? (b.prio === "—" ? Infinity : Number(b.prio)) };
  });
  return { mvp, backlog };
}

/** The card the dev agent should work on: a card already in progress first (resume), else the top Ready card. */
export function nextCard({ backlog }) {
  const doing = backlog.find((b) => b.status === "in_progress");
  if (doing) return doing;
  return readyCards(backlog)[0];
}

export function readyCards(backlog) {
  return backlog.filter((b) => b.status === "ready").sort((a, b) => a.prioNum - b.prioNum || a.id.localeCompare(b.id, "en", { numeric: true }));
}

const bar = (n, d) => {
  const f = Math.min(20, Math.max(0, Math.round((n / (d || 1)) * 20)));
  return `${"█".repeat(f)}${"░".repeat(20 - f)} ${n}/${d}`;
};

/** First "## Blocked…" section's first non-empty line, for the board. */
export function blockerLine(taskText = "") {
  const parts = taskText.split(/^## /m);
  const sec = parts.filter((p) => /^Blocked/i.test(p)).pop();
  if (!sec) return "";
  return sec.split("\n").slice(1).map((l) => l.replace(/^[-*]\s*/, "").trim()).find(Boolean) ?? "";
}

export function render({ mvp, backlog }, taskFiles = {}) {
  const queue = backlog.filter((b) => !b.triggered);
  const triggered = backlog.filter((b) => b.triggered);
  const by = (s) => queue.filter((b) => b.status === s);
  const days = (xs) => xs.reduce((n, b) => n + (SIZE_DAYS[b.size] ?? 0), 0);
  const planned = queue.filter((b) => !b.adhoc);
  const bDone = planned.filter((b) => b.status === "done");
  const mvpCode = mvp.filter((t) => ["review", "done"].includes(t.status) && t.id !== "T0").length;
  const mvpDone = mvp.filter((t) => t.status === "done").length;
  const next = nextCard({ backlog });

  const L = [];
  L.push("# IntelliTrack: Kanban", "",
    "_Generated by `npm run kanban` from `plan.md`, `tasks/*.md` and `kanban.state.json`. Don't edit this file. Move cards with `npm run kanban -- set <ID> <status>`._", "");
  L.push("## Progress", "", "| | |", "|---|---|");
  L.push(`| MVP code complete (T1–T6) | \`${bar(mvpCode, mvp.length - 1)}\` |`);
  L.push(`| MVP gates passed (T0–T6) | \`${bar(mvpDone, mvp.length)}\` |`);
  L.push(`| Backlog items done | \`${bar(bDone.length, planned.length)}\` |`);
  L.push(`| Backlog effort done (rough days: S=2, M=4, L=8) | \`${bar(days(bDone), days(planned))}\` |`, "");
  L.push("## Next for the dev agent", "");
  L.push(next ? `**${next.id}** ${next.item}${next.status === "in_progress" ? " (in progress, resume)" : ""}` : "_Nothing is Ready. Add a card from the review session._", "");
  if (mvp.some((t) => t.status !== "done")) L.push(`_MVP gates still open: ${mvp.filter((t) => t.status !== "done").map((t) => t.id).join(", ")}. They need real keys and sites, so they're run by hand, not by the agent._`, "");

  const line = (b) => `- **${b.id}** ${b.item}`;
  const col = (name, rows, fmt = line) => {
    L.push(`### ${name} (${rows.length})`, "");
    L.push(...(rows.length ? rows.map(fmt) : ["_empty_"]), "");
  };
  L.push("## Board", "", "WIP limit: 1 card in progress. A card is Ready only with a `tasks/<ID>.md` holding checkable acceptance criteria.", "");
  col("In progress", [...mvp.filter((t) => t.status === "in_progress"), ...by("in_progress")], (b) => `${line(b)}${b.branch ? ` · \`${b.branch}\`` : ""}`);
  col("Blocked (needs you)", by("blocked"), (b) => `${line(b)}${b.branch ? ` · \`${b.branch}\`` : ""}\n  - ${blockerLine(taskFiles[b.id]) || b.note || "see tasks/" + b.id + ".md"}`);
  col("Ready", readyCards(queue), (b) => `${line(b)} (${b.size})${b.hasTask ? "" : " ⚠ no tasks/" + b.id + ".md"}`);
  col("Review", [...by("review"), ...mvp.filter((t) => t.status === "review")],
    (b) => b.mvp ? `${line(b)}: ${b.statusText}\n  - Gate still open: ${b.done}` : `${line(b)}${b.branch ? ` · \`${b.branch}\`` : ""}${b.note ? `\n  - ${b.note}` : ""}`);
  col("Done", [...mvp.filter((t) => t.status === "done"), ...by("done")]);

  const rest = by("backlog");
  L.push(`### Backlog (${rest.length})`, "", "| Prio | ID | Item | Type | Size | Depends on |", "|---|---|---|---|---|---|");
  for (const b of rest) L.push(`| ${b.prio} | ${b.id} | ${b.item} | ${b.type} | ${b.size} | ${b.deps} |`);
  L.push("", "### Triggered (skip the queue only when the trigger fires)", "");
  for (const b of triggered) L.push(`- **${b.id}** ${b.item}: ${b.why}`);
  L.push("");
  return L.join("\n");
}
