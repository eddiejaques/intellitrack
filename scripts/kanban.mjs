// Generates kanban.md from plan.md (MVP table in §1, prioritization table in §9).
// Optional kanban.state.json maps a backlog ID to "in_progress" | "review" | "done" (default: backlog).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const plan = readFileSync("plan.md", "utf8");
const state = existsSync("kanban.state.json") ? JSON.parse(readFileSync("kanban.state.json", "utf8")) : {};
const cells = (line) => line.split("|").slice(1, -1).map((c) => c.trim());
const clean = (t) => t.replace(/\*\*/g, "").replace(/`/g, "");

// ---- MVP tasks (§1)
const mvp = plan.split("\n").filter((l) => /^\| \*\*T\d\*\* \|/.test(l)).map((l) => {
  const [id, name, , done, deps, status] = cells(l).map(clean);
  const col = /^done/i.test(status) ? "Done" : /^in progress/i.test(status) ? "In progress" : /^code complete/i.test(status) ? "Review / Eval" : /^repo initialized/i.test(status) ? "Review / Eval" : "Backlog";
  return { id, name, done, deps, status, col };
});

// ---- Backlog (§9)
const sect = plan.slice(plan.indexOf("### Prioritization"));
const SIZE_DAYS = { S: 2, M: 4, L: 8 };
const backlog = sect.split("\n").filter((l) => /^\| (\d+|—) \| /.test(l)).map((l) => {
  const [prio, id, item, type, size, why, deps] = cells(l).map(clean);
  const st = state[id] ?? "backlog";
  const col = { done: "Done", review: "Review / Eval", in_progress: "In progress", backlog: "Backlog" }[st];
  return { prio, id, item, type, size, why, deps, col, triggered: prio === "—" };
});
const queue = backlog.filter((b) => !b.triggered);
const triggered = backlog.filter((b) => b.triggered);

// ---- progress
const bar = (n, d) => `${"█".repeat(Math.round((n / (d || 1)) * 20))}${"░".repeat(20 - Math.round((n / (d || 1)) * 20))} ${n}/${d}`;
const mvpCode = mvp.filter((t) => ["Review / Eval", "Done"].includes(t.col) && t.id !== "T0").length;
const mvpDone = mvp.filter((t) => t.col === "Done").length;
const days = (xs) => xs.reduce((n, b) => n + (SIZE_DAYS[b.size] ?? 0), 0);
const bDone = queue.filter((b) => b.col === "Done");

// ---- next task
const openMvp = mvp.filter((t) => t.col !== "Done");
const nextB = queue.find((b) => b.col === "Backlog");
const readyNext = queue.filter((b) => b.col === "Backlog").slice(0, 3);
let next;
if (openMvp.length) {
  next = `**Close the MVP gates first.** ${openMvp.length} of ${mvp.length} MVP tasks have no passed "Done when" check yet (listed below). ` +
    `Nothing from the backlog should start until T1's capture gate has run, because **T-1** (move B2 into the MVP) triggers if it fails.\n\n` +
    `Then pull **${nextB?.id} ${nextB?.item}** (${nextB?.size}).`;
} else next = `**${nextB?.id} ${nextB?.item}** (${nextB?.size}): ${nextB?.why}`;

const L = [];
L.push("# IntelliTrack: Kanban", "", "_Generated by `npm run kanban` from `plan.md`. Edit the plan, not this file. To move a backlog item, add it to `kanban.state.json`, e.g. `{ \"B1\": \"in_progress\" }`._", "");
L.push("## Progress", "");
L.push(`| | |`, `|---|---|`);
L.push(`| MVP code complete (T1–T6) | \`${bar(mvpCode, mvp.length - 1)}\` |`);
L.push(`| MVP gates passed (T0–T6) | \`${bar(mvpDone, mvp.length)}\` |`);
L.push(`| Backlog items done | \`${bar(bDone.length, queue.length)}\` |`);
L.push(`| Backlog effort done (rough days: S=2, M=4, L=8) | \`${bar(days(bDone), days(queue))}\` |`, "");
L.push("## Next task", "", next, "");

const col = (name, rows, fmt) => {
  L.push(`### ${name} (${rows.length})`, "");
  if (!rows.length) L.push("_empty_", "");
  else L.push(...rows.map(fmt), "");
};
L.push("## Board", "", "WIP limit in progress: 2. Ready: max 3, and an item is Ready only with acceptance criteria and fixtures (real captured requests for vendors).", "");
col("Done", [...mvp.filter((t) => t.col === "Done"), ...queue.filter((b) => b.col === "Done")], (t) => `- **${t.id}** ${t.name ?? t.item}`);
col("In progress", [...mvp.filter((t) => t.col === "In progress"), ...queue.filter((b) => b.col === "In progress")], (t) => `- **${t.id}** ${t.name ?? t.item}`);
col("Review / Eval", [...mvp.filter((t) => t.col === "Review / Eval"), ...queue.filter((b) => b.col === "Review / Eval")],
  (t) => `- **${t.id}** ${t.name ?? t.item}: ${t.status ?? ""}${t.done ? `\n  - Gate still open: ${t.done}` : ""}`);
col("Ready", [], () => "");
L.push("_Nothing is Ready yet. Candidates, in order, once they have acceptance criteria and fixtures:_", "");
L.push(...readyNext.map((b) => `- **${b.id}** ${b.item} (${b.size}): needs ${b.type === "vendor" ? "real captured requests as fixtures" : "acceptance criteria"}`), "");

L.push(`### Backlog (${queue.filter((b) => b.col === "Backlog").length})`, "", "| Prio | ID | Item | Type | Size | Depends on |", "|---|---|---|---|---|---|");
for (const b of queue.filter((b) => b.col === "Backlog")) L.push(`| ${b.prio} | ${b.id} | ${b.item} | ${b.type} | ${b.size} | ${b.deps} |`);
L.push("", "### Triggered (skip the queue only when the trigger fires)", "");
for (const b of triggered) L.push(`- **${b.id}** ${b.item}: ${b.why}`);
L.push("");
writeFileSync("kanban.md", L.join("\n"));
console.log(`kanban.md: MVP code ${mvpCode}/${mvp.length - 1}, gates ${mvpDone}/${mvp.length}, backlog ${bDone.length}/${queue.length}`);
